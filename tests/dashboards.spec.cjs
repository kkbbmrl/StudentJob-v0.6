const { test, expect } = require('@playwright/test');
const { pathToFileURL } = require('node:url');
const path = require('node:path');
test('three roles, profiles, hiring and moderation work together', async ({ page }) => {
  await page.goto(pathToFileURL(path.resolve('index.html')).href);
  await page.getByRole('button', {name:'Espace démo', exact:true}).click();
  await expect(page.locator('#workspace')).toBeVisible();
  await page.getByRole('button', {name:'Mon profil', exact:true}).click();
  await page.getByLabel('Nom complet').fill('Yasmine Demo');
  await page.getByRole('button', {name:'Enregistrer le profil'}).click();
  await page.reload();
  await page.getByRole('button', {name:'Espace démo', exact:true}).click();
  await expect(page.locator('#workspace')).toContainText('Yasmine Demo');
  await page.getByLabel('Espace de démonstration').selectOption('recruiter');
  await page.getByRole('button', {name:'Candidatures', exact:true}).click();
  await page.getByRole('button', {name:'Accepter', exact:true}).first().click();
  await expect(page.locator('#workspace')).toContainText('Acceptée');
  await page.getByLabel('Espace de démonstration').selectOption('admin');
  await page.getByRole('button', {name:'Utilisateurs', exact:true}).click();
  await page.getByRole('button', {name:'Vérifier', exact:true}).first().click();
  await expect(page.locator('#workspace')).toContainText('Vérifié');
});
